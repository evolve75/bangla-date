from datetime import datetime


def গ্রেগরিয়ান_থেকে_বাংলা_তারিখ(গ্রেগরিয়ান_তারিখ):
    """
    গ্রেগরিয়ান তারিখকে বাংলা তারিখে রূপান্তর করে।
    :param গ্রেগরিয়ান_তারিখ: গ্রেগরিয়ান তারিখ (datetime অবজেক্ট)
    :return: বাংলা তারিখের দিন, মাস, বছর এবং ঋতু
    """
    # বাংলা সনের মাসের নাম
    বাংলা_মাসসমূহ = [
        "বৈশাখ", "জ্যৈষ্ঠ", "আষাঢ়", "শ্রাবণ", "ভাদ্র", "আশ্বিন",
        "কার্তিক", "অগ্রহায়ণ", "পৌষ", "মাঘ", "ফাল্গুন", "চৈত্র"
    ]

    # বাংলা ঋতু এবং সংশ্লিষ্ট মাস
    ঋতু_মানচিত্র = {
        "গ্রীষ্ম": ["বৈশাখ", "জ্যৈষ্ঠ"],
        "বর্ষা": ["আষাঢ়", "শ্রাবণ"],
        "শরৎ": ["ভাদ্র", "আশ্বিন"],
        "হেমন্ত": ["কার্তিক", "অগ্রহায়ণ"],
        "শীত": ["পৌষ", "মাঘ"],
        "বসন্ত": ["ফাল্গুন", "চৈত্র"]
    }

    # গ্রেগরিয়ান মাসের সাথে বাংলা মাসের সম্পর্ক এবং মাস পরিবর্তনের দিন
    মাস_মানচিত্র = {
        1: ("পৌষ", 14), 2: ("মাঘ", 13), 3: ("ফাল্গুন", 14), 4: ("চৈত্র", 13),
        5: ("বৈশাখ", 14), 6: ("জ্যৈষ্ঠ", 14), 7: ("আষাঢ়", 14), 8: ("শ্রাবণ", 15),
        9: ("ভাদ্র", 15), 10: ("আশ্বিন", 15), 11: ("কার্তিক", 15), 12: ("অগ্রহায়ণ", 15)
    }

    # গ্রেগরিয়ান তারিখ থেকে দিন, মাস এবং বছর নির্ণয়
    গ্রেগরিয়ান_দিন = গ্রেগরিয়ান_তারিখ.day
    গ্রেগরিয়ান_মাস = গ্রেগরিয়ান_তারিখ.month
    গ্রেগরিয়ান_বছর = গ্রেগরিয়ান_তারিখ.year

    # বর্তমান গ্রেগরিয়ান মাসের সাথে সংশ্লিষ্ট বাংলা মাস এবং মাস পরিবর্তনের দিন নির্ণয়
    বাংলা_মাস, পরিবর্তন_দিন = মাস_মানচিত্র[গ্রেগরিয়ান_মাস]

    # যদি গ্রেগরিয়ান দিনের সংখ্যা মাস পরিবর্তনের দিনের চেয়ে কম হয়
    if গ্রেগরিয়ান_দিন < পরিবর্তন_দিন:
        # পূর্ববর্তী বাংলা মাস নির্ণয়
        বাংলা_মাস_সূচক = (বাংলা_মাসসমূহ.index(বাংলা_মাস) - 1) % 12
        বাংলা_মাস = বাংলা_মাসসমূহ[বাংলা_মাস_সূচক]
        # বাংলা দিনের সংখ্যা নির্ণয়
        বাংলা_দিন = গ্রেগরিয়ান_দিন + (30 if বাংলা_মাস in ["ফাল্গুন", "আষাঢ়", "ভাদ্র", "কার্তিক"] else 31) - পরিবর্তন_দিন
    else:
        # বাংলা দিনের সংখ্যা নির্ণয়
        বাংলা_দিন = গ্রেগরিয়ান_দিন - পরিবর্তন_দিন + 1

    # বাংলা বছরের সংখ্যা নির্ণয়
    বাংলা_বছর = গ্রেগরিয়ান_বছর - 593 if গ্রেগরিয়ান_মাস > 4 or (গ্রেগরিয়ান_মাস == 4 and গ্রেগরিয়ান_দিন >= 14) else গ্রেগরিয়ান_বছর - 594

    # বাংলা মাসের ভিত্তিতে ঋতু নির্ণয়
    বাংলা_ঋতু = next((ঋতু for ঋতু, মাসসমূহ in ঋতু_মানচিত্র.items() if বাংলা_মাস in মাসসমূহ), None)

    return বাংলা_দিন, বাংলা_মাস, বাংলা_বছর, বাংলা_ঋতু


def ইংরেজি_থেকে_বাংলা_সংখ্যা(সংখ্যা):
    """
    ইংরেজি সংখ্যাকে বাংলা সংখ্যায় রূপান্তর করে।
    :param সংখ্যা: ইংরেজি সংখ্যা (integer)
    :return: বাংলা সংখ্যা (string)
    """
    বাংলা_অঙ্ক = '০১২৩৪৫৬৭৮৯'
    return ''.join(বাংলা_অঙ্ক[int(অঙ্ক)] for অঙ্ক in str(সংখ্যা))


if __name__ == "__main__":
    # বর্তমান তারিখ নির্ণয়
    আজ = datetime.now()
    # গ্রেগরিয়ান তারিখকে বাংলা তারিখে রূপান্তর
    বাংলা_দিন, বাংলা_মাস, বাংলা_বছর, বাংলা_ঋতু = গ্রেগরিয়ান_থেকে_বাংলা_তারিখ(আজ)
    # বাংলা দিনের সংখ্যা রূপান্তর
    বাংলা_দিন_বাংলা = ইংরেজি_থেকে_বাংলা_সংখ্যা(বাংলা_দিন)
    # বাংলা বছরের সংখ্যা রূপান্তর
    বাংলা_বছর_বাংলা = ইংরেজি_থেকে_বাংলা_সংখ্যা(বাংলা_বছর)
    # বাংলা তারিখ এবং ঋতু প্রদর্শন
    print(f"আজকের বাংলা তারিখ: {বাংলা_দিন_বাংলা} {বাংলা_মাস}, {বাংলা_বছর_বাংলা} বঙ্গাব্দ")
    print(f"বর্তমান ঋতু: {বাংলা_ঋতু}")
